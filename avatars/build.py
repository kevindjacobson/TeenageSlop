#!/usr/bin/env python3
"""Bake avatars/svg/*.svg into a TypeScript polyline table for the teenageslop mod.

Each SVG is restricted (see README.md) to path M/L/C/Q/Z, polyline, line, circle and
ellipse with absolute coordinates in a 0 0 64 64 viewBox, so this flattens every element
into a list of points the mod's rasterizer can stroke with its own line routine.

Usage: python3 avatars/build.py avatars/svg <mod>/hooks/avatars.ts
"""
import json
import math
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

NS = '{http://www.w3.org/2000/svg}'
CURVE_STEPS = 10


def bezier3(p0, p1, p2, p3, t):
    u = 1 - t
    return (
        u * u * u * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t * t * t * p3[0],
        u * u * u * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t * t * t * p3[1],
    )


def bezier2(p0, p1, p2, t):
    u = 1 - t
    return (u * u * p0[0] + 2 * u * t * p1[0] + t * t * p2[0], u * u * p0[1] + 2 * u * t * p1[1] + t * t * p2[1])


def path_polylines(d):
    tokens = re.findall(r'[MLCQZmlcqz]|-?\d*\.?\d+(?:e-?\d+)?', d)
    polys, cur, start, i, cmd = [], [], None, 0, None
    nums = lambda n: [float(tokens[i + k]) for k in range(n)]  # noqa: E731
    while i < len(tokens):
        t = tokens[i]
        if t.isalpha():
            cmd = t.upper()
            i += 1
            if cmd == 'Z':
                if cur and start:
                    cur.append(start)
                if len(cur) > 1:
                    polys.append(cur)
                cur, start = [], None
            continue
        if cmd == 'M':
            x, y = nums(2); i += 2
            if len(cur) > 1:
                polys.append(cur)
            cur, start = [(x, y)], (x, y)
            cmd = 'L'
        elif cmd == 'L':
            x, y = nums(2); i += 2
            cur.append((x, y))
        elif cmd == 'C':
            x1, y1, x2, y2, x, y = nums(6); i += 6
            p0 = cur[-1]
            cur.extend(bezier3(p0, (x1, y1), (x2, y2), (x, y), k / CURVE_STEPS) for k in range(1, CURVE_STEPS + 1))
        elif cmd == 'Q':
            x1, y1, x, y = nums(4); i += 4
            p0 = cur[-1]
            cur.extend(bezier2(p0, (x1, y1), (x, y), k / CURVE_STEPS) for k in range(1, CURVE_STEPS + 1))
        else:
            raise ValueError(f'unsupported path command {cmd}')
    if len(cur) > 1:
        polys.append(cur)
    return polys


def ellipse_polyline(cx, cy, rx, ry):
    n = max(12, int((rx + ry) * 2))
    return [(cx + rx * math.cos(2 * math.pi * k / n), cy + ry * math.sin(2 * math.pi * k / n)) for k in range(n + 1)]


def element_polylines(el):
    tag = el.tag.replace(NS, '')
    a = el.attrib
    if tag == 'path':
        return path_polylines(a['d'])
    if tag == 'polyline':
        pts = [float(v) for v in re.findall(r'-?\d*\.?\d+', a['points'])]
        return [list(zip(pts[0::2], pts[1::2]))]
    if tag == 'line':
        return [[(float(a['x1']), float(a['y1'])), (float(a['x2']), float(a['y2']))]]
    if tag == 'circle':
        return [ellipse_polyline(float(a['cx']), float(a['cy']), float(a['r']), float(a['r']))]
    if tag == 'ellipse':
        return [ellipse_polyline(float(a['cx']), float(a['cy']), float(a['rx']), float(a['ry']))]
    return []


def build(svg_dir, out):
    table = {}
    for f in sorted(Path(svg_dir).glob('*.svg')):
        kind, pose = f.stem.rsplit('-', 1)
        root = ET.parse(f).getroot()
        strokes = []
        for el in root.iter():
            if el is root:
                continue
            color = el.attrib.get('stroke', 'currentColor')
            for poly in element_polylines(el):
                pts = [round(v, 2) for p in poly for v in p]
                strokes.append({'c': None if color == 'currentColor' else color, 'p': pts})
        table.setdefault(kind, {})[pose] = strokes
    body = json.dumps(table, separators=(',', ':'))
    Path(out).write_text(
        '// Generated by avatars/build.py from avatars/svg; do not edit by hand.\n'
        '// Each stroke is a flat [x0,y0,x1,y1,...] polyline in a 64x64 space; `c` null means the figure colour.\n'
        'export type Stroke = { c: string | null; p: number[] }\n'
        'export type Avatars = Record<string, Record<string, Stroke[]>>\n'
        f'export const AVATARS: Avatars = {body}\n'
    )
    n = sum(len(v) for v in table.values())
    print(f'{n} figures, {len(table)} kinds -> {out}')


if __name__ == '__main__':
    build(sys.argv[1], sys.argv[2])
